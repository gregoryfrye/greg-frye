#!/usr/bin/env node
// Design tokens. kit/visual-system.json is the source of truth; app/tokens.css
// is generated from it (never hand-edit that file).
//
//   node scripts/tokens.mjs --write              regenerate app/tokens.css
//   node scripts/tokens.mjs                      print tokens resolved for Figma (JSON)
//   node scripts/tokens.mjs --check <figma.json> compare a Figma variables export to code
//
// Figma can't do fluid type (clamp), so sizes resolve at two widths, matching
// Figma Layout modes: Expanded = 1280px, Compact = 375px. The Friday sync exports
// Figma's variables to design/figma-variables.json and runs --check; any
// mismatch means Figma is behind the live site (or holds an unshipped idea).
// No dependencies, so it runs anywhere Node runs.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const KIT = JSON.parse(fs.readFileSync(path.join(ROOT, "kit/visual-system.json"), "utf8"));
const OUT = path.join(ROOT, "app/tokens.css");
const WIDTHS = { Expanded: 1280, Compact: 375 };
const REM = 16;

const round = (n) => Math.round(n * 100) / 100;
const round4 = (n) => Math.round(n * 10000) / 10000;
const rem = (px) => `${round4(px / REM)}rem`;
const isJob = (v) => v && typeof v === "object" && "value" in v;
const val = (v) => (isJob(v) ? v.value : v);
const entries = (o) => Object.entries(o).filter(([k]) => !k.startsWith("$"));

const P = KIT.primitives;
const colorOf = (name) => P.color[name] ?? P.alpha[name] ?? (() => { throw new Error(`Unknown color primitive: ${name}`); })();

/** Fluid size between the compact and expanded viewports. */
function fluid([lo, hi]) {
  if (lo === hi) return rem(lo);
  const { compact, expanded } = P.viewport;
  const slope = (hi - lo) / (expanded - compact);
  const intercept = lo - slope * compact;
  return `clamp(${rem(lo)}, ${rem(intercept)} + ${round4(slope * 100)}vw, ${rem(hi)})`;
}

// ---------------------------------------------------------------- generate CSS

function css() {
  const L = [];
  const t = (s = "") => L.push(s);
  t("/*");
  t(" * GENERATED by scripts/tokens.mjs from kit/visual-system.json. Do not edit:");
  t(" * change the JSON, then run `npm run tokens:build`. Why each token exists:");
  t(" * kit/*.md. Components use these through Tailwind classes only.");
  t(" */");
  t("");
  t("@theme {");
  t("  /* Breakpoints — Greg's scale; compact/expanded layouts switch at md (960) */");
  t("  --breakpoint-*: initial;");
  for (const [k, v] of entries(P.breakpoints)) t(`  --breakpoint-${k}: ${rem(v)};`);
  t("");
  t("  /* Color, by job (kit/color.md) */");
  for (const [k, v] of entries(KIT.semantic.color)) t(`  --color-${k}: ${colorOf(v.value)}; /* ${v.job} */`);
  t("");
  t("  /* Families */");
  for (const [k, v] of entries(P.fonts)) t(`  --font-${k}: ${v};`);
  t("");
  t("  /* Legacy type sizes — migrate components to type-* roles, then delete */");
  for (const [k, v] of entries(KIT.type.legacy)) {
    if (typeof v === "string") continue;
    t(`  --text-${k}: ${v.size};`);
    t(`  --text-${k}--line-height: ${v.lineHeight};`);
  }
  t(`  --tracking-tight: ${KIT.type.legacy["tracking-tight"]};`);
  t("");
  t("  /* Spacing on the 9px rhythm, by job (kit/layout.md) */");
  for (const [k, v] of entries(KIT.layout.spacing)) t(`  --spacing-${k}: ${rem(val(v))}; /* ${v.job} */`);
  t("");
  t("  /* Containers — layout (wide) vs. reading measure (prose) */");
  for (const [k, v] of entries(KIT.layout.containers)) t(`  --container-${k}: ${rem(val(v))}; /* ${v.job} */`);
  t("");
  t("  /* Easing, by purpose (kit/motion.md) */");
  for (const [k, v] of entries(KIT.motion.ease)) t(`  --ease-${k}: ${v.value}; /* ${v.job} */`);
  t("}");
  t("");
  t(":root {");
  t("  /* Type roles: size fluid from 375 to 1280 (kit/type.md) */");
  for (const [k, r] of entries(KIT.type.roles)) {
    t(`  --type-${k}-size: ${fluid(r.size)};`);
    t(`  --type-${k}-line-height: ${r.lineHeight};`);
    t(`  --type-${k}-tracking: ${r.tracking};`);
  }
  t("");
  t("  /* Durations */");
  for (const [k, v] of entries(KIT.motion.duration)) t(`  --duration-${k}: ${v.value}ms; /* ${v.job} */`);
  t("");
  t(`  --line-weight: ${KIT.line.weight.value}px; /* ${KIT.line.weight.job} */`);
  t("}");
  t("");
  t("/* type-<role>: the whole bundle in one class */");
  for (const [k, r] of entries(KIT.type.roles)) {
    t(`@utility type-${k} {`);
    t(`  font-family: var(--font-${r.family});`);
    t(`  font-size: var(--type-${k}-size);`);
    t(`  line-height: var(--type-${k}-line-height);`);
    t(`  letter-spacing: var(--type-${k}-tracking);`);
    t(`  font-weight: ${r.weight ?? 400};`);
    t(`  font-style: ${r.style ?? "normal"};`);
    t("}");
  }
  t("");
  t("/* motion-<duration>: pair with ease-<purpose> and transition-<property> */");
  for (const [k] of entries(KIT.motion.duration)) {
    t(`@utility motion-${k} {`);
    t(`  transition-duration: var(--duration-${k});`);
    t("}");
  }
  t("");
  t("/* rule: the Figma divider line */");
  t("@utility rule {");
  t("  border-top: var(--line-weight) solid var(--color-border);");
  t("}");
  return L.join("\n") + "\n";
}

// ---------------------------------------------------------------- resolve for Figma

function px(value, width) {
  const v = String(value).trim();
  const clamp = v.match(/^clamp\(([^,]+),([^,]+),([^)]+)\)$/);
  if (clamp) {
    const [lo, mid, hi] = clamp.slice(1).map((p) => px(p, width));
    return round(Math.min(Math.max(lo, mid), hi));
  }
  if (/\+/.test(v)) return round(v.split("+").reduce((s, p) => s + px(p, width), 0));
  if (v.endsWith("rem")) return round(parseFloat(v) * REM);
  if (v.endsWith("vw")) return round((parseFloat(v) * width) / 100);
  if (v.endsWith("px")) return round(parseFloat(v));
  if (v.endsWith("em")) return round(parseFloat(v) * 100); // letter-spacing → percent
  return round(parseFloat(v));
}

function color(value) {
  const v = value.trim();
  const hex = v.match(/^#([0-9a-f]{6})$/i);
  if (hex) {
    const n = parseInt(hex[1], 16);
    return { r: round4(((n >> 16) & 255) / 255), g: round4(((n >> 8) & 255) / 255), b: round4((n & 255) / 255), a: 1 };
  }
  const rgb = v.match(/^rgb\((\d+)\s+(\d+)\s+(\d+)(?:\s*\/\s*([\d.]+))?\)$/);
  if (rgb) {
    const [r, g, b] = rgb.slice(1, 4).map((x) => round4(Number(x) / 255));
    return { r, g, b, a: rgb[4] === undefined ? 1 : Number(rgb[4]) };
  }
  throw new Error(`Unparsed color: ${v}`);
}

export function resolveTokens() {
  const out = { color: {}, type: {}, space: {}, font: {}, role: {}, motion: {}, breakpoint: {} };
  for (const [k, v] of entries(KIT.semantic.color)) out.color[k] = color(colorOf(v.value));
  // First named family, skipping CSS generics like ui-monospace (Figma can't hold those)
  for (const [k, v] of entries(P.fonts)) out.font[k] = v.split(",").map((f) => f.replace(/"/g, "").trim()).find((f) => !f.startsWith("ui-"));
  for (const [k, v] of entries(KIT.type.legacy)) {
    if (typeof v === "string") continue;
    for (const [mode, w] of Object.entries(WIDTHS)) {
      const size = px(v.size, w);
      out.type[k] ??= {};
      out.type[k][mode] = { size, lineHeight: round(size * v.lineHeight) };
    }
  }
  out.space["tracking-tight"] = px(KIT.type.legacy["tracking-tight"], WIDTHS.Expanded);
  for (const [k, v] of entries(KIT.layout.spacing)) out.space[k] = val(v);
  for (const [k, v] of entries(KIT.layout.containers)) out.space[`container-${k}`] = val(v);
  for (const [k, r] of entries(KIT.type.roles)) {
    const [mobile, desktop] = r.size;
    out.role[k] = {
      family: out.font[r.family],
      style: r.style ?? "normal",
      tracking: px(r.tracking === "0" ? "0em" : r.tracking, WIDTHS.Expanded),
      Expanded: { size: desktop, lineHeight: round(desktop * r.lineHeight) },
      Compact: { size: mobile, lineHeight: round(mobile * r.lineHeight) },
    };
  }
  for (const [k, v] of entries(KIT.motion.duration)) out.motion[`duration-${k}`] = v.value;
  for (const [k, v] of entries(P.breakpoints)) out.breakpoint[k] = v;
  out.space["line-weight"] = KIT.line.weight.value;
  return out;
}

function flatten(obj, prefix = "") {
  const rows = {};
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}/${k}` : k;
    if (v && typeof v === "object" && !("r" in v)) Object.assign(rows, flatten(v, key));
    else rows[key] = v;
  }
  return rows;
}

const same = (a, b) =>
  typeof a === "object" && typeof b === "object"
    ? ["r", "g", "b", "a"].every((c) => Math.abs((a?.[c] ?? 1) - (b?.[c] ?? 1)) < 0.006)
    : typeof a === "number" && typeof b === "number"
      ? Math.abs(a - b) < 0.05
      : a === b;

const args = process.argv.slice(2);
if (args[0] === "--write") {
  fs.writeFileSync(OUT, css());
  console.log(`Wrote ${path.relative(ROOT, OUT)} from kit/visual-system.json`);
} else if (args[0] === "--check") {
  const figmaPath = args[1] ?? path.join(ROOT, "design/figma-variables.json");
  const code = flatten(resolveTokens());
  const figma = flatten(JSON.parse(fs.readFileSync(figmaPath, "utf8")));
  const fmt = (v) => (typeof v === "object" ? JSON.stringify(v) : String(v));
  const rows = [];
  for (const k of new Set([...Object.keys(code), ...Object.keys(figma)])) {
    if (!(k in figma)) rows.push(["MISSING IN FIGMA", k, fmt(code[k]), "—"]);
    else if (!(k in code)) rows.push(["FIGMA ONLY", k, "—", fmt(figma[k])]);
    else if (!same(code[k], figma[k])) rows.push(["DRIFT", k, fmt(code[k]), fmt(figma[k])]);
  }
  console.log(`Token sync — code (kit/visual-system.json) vs Figma (${path.relative(ROOT, figmaPath)})`);
  if (!rows.length) console.log("In sync: every token matches.");
  for (const [kind, k, c, f] of rows) console.log(`  ${kind.padEnd(16)} ${k.padEnd(28)} code ${c}  figma ${f}`);
  // Report only. FIGMA ONLY rows are often unshipped explorations, not errors.
  process.exit(0);
} else {
  console.log(JSON.stringify(resolveTokens(), null, 2));
}
